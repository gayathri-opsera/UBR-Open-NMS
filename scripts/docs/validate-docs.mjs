#!/usr/bin/env node
/**
 * NMS Documentation Validator
 *
 * Usage (from repo root):
 *   node scripts/docs/validate-docs.mjs
 *   cd frontend && npm run docs:validate
 *
 * What it checks:
 *  1. All pages have required fields (slug, title, lastUpdated, content)
 *  2. No broken internal /v2/docs/:slug links
 *  3. No pages stale for > 90 days
 *  4. Coverage: all required slugs have a matching doc page
 */

import { readFileSync, readdirSync, statSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dir, '../..');

// ── Config ────────────────────────────────────────────────────────────────────
const STALE_DAYS = 90;
const MIN_CONTENT_CHARS = 100;

const REQUIRED_SLUGS = [
  'introduction', 'quick-start-operator', 'quick-start-admin', 'quick-start-discovery',
  'alarm-management', 'kpi-monitoring', 'kpi-operations', 'topology',
  'device-inventory', 'device-detail', 'node-view', 'device-groups', 'reports',
  'discovery', 'discovery-audit', 'onboarding', 'config-management',
  'troubleshoot', 'release-validation', 'compliance',
  'product-definitions', 'descriptor-registry', 'mib-builder', 'node-view-designer',
  'framework-ops', 'org-hierarchy', 'notifications', 'security-audit',
  'administration', 'user-profile',
  'glossary', 'api-reference', 'architecture', 'release-notes',
];

// ── File helpers ──────────────────────────────────────────────────────────────
function getAllTsFiles(dir) {
  const result = [];
  try {
    const entries = readdirSync(dir);
    for (const e of entries) {
      const full = resolve(dir, e);
      const stat = statSync(full);
      if (stat.isDirectory()) result.push(...getAllTsFiles(full));
      else if (e.endsWith('.ts') && !e.endsWith('.d.ts')) result.push(full);
    }
  } catch { /* ignore */ }
  return result;
}

// ── Extract pages via regex (no TS compilation needed) ────────────────────────
function extractPages(root) {
  const files = getAllTsFiles(resolve(root, 'frontend/src/data/docs'));
  const allPages = [];

  for (const file of files) {
    const src = readFileSync(file, 'utf8');

    // Extract all slugs declared in this file
    const slugRe   = /slug:\s*['"`]([^'"`\n]+)['"`]/g;
    const titleRe  = /title:\s*['"`]([^'"`\n]+)['"`]/g;
    const lastUpdRe = /lastUpdated:\s*['"`]([^'"`\n]+)['"`]/g;
    const autoGenRe = /autoGenerated:\s*true/g;
    const contentRe = /content:\s*`([\s\S]*?)`(?:\s*,|\s*\n\s*[a-z}])/g;

    const slugs      = [...src.matchAll(slugRe)].map(m => m[1]);
    const titles     = [...src.matchAll(titleRe)].map(m => m[1]);
    const lastUpdates = [...src.matchAll(lastUpdRe)].map(m => m[1]);
    const autoGenIdxs = [...src.matchAll(autoGenRe)].map(m => m.index);
    const contents   = [...src.matchAll(contentRe)].map(m => m[1]);

    for (let i = 0; i < slugs.length; i++) {
      allPages.push({
        slug: slugs[i],
        title: titles[i] ?? '',
        lastUpdated: lastUpdates[i] ?? '',
        autoGenerated: autoGenIdxs.length > 0,
        content: contents[i] ?? '',
        _file: file.replace(root, ''),
      });
    }
  }
  return allPages;
}

// ── Validation ────────────────────────────────────────────────────────────────
const ERRORS   = [];
const WARNINGS = [];

const pages = extractPages(ROOT);
const allSlugs = new Set(pages.map(p => p.slug));

console.log('\n📚 NMS Documentation Validator');
console.log('═'.repeat(50));

// 1. Required fields
for (const page of pages) {
  if (!page.slug)        ERRORS.push(`${page._file}: page missing slug`);
  if (!page.title)       ERRORS.push(`Page "${page.slug}": missing title`);
  if (!page.lastUpdated) ERRORS.push(`Page "${page.slug}": missing lastUpdated`);
  if (!page.autoGenerated && page.content.length < MIN_CONTENT_CHARS)
    ERRORS.push(`Page "${page.slug}": content too short (${page.content.length} chars, min ${MIN_CONTENT_CHARS})`);
}

// 2. Broken internal /v2/docs/ links
for (const page of pages) {
  const linkRe = /\[([^\]]+)\]\(\/v2\/docs\/([^)\s]+)\)/g;
  let m;
  while ((m = linkRe.exec(page.content)) !== null) {
    if (!allSlugs.has(m[2]))
      ERRORS.push(`Page "${page.slug}": broken internal link → /v2/docs/${m[2]}`);
  }
}

// 3. Stale check
const cutoff = Date.now() - STALE_DAYS * 24 * 60 * 60 * 1000;
for (const page of pages) {
  if (!page.lastUpdated) continue;
  const d = new Date(page.lastUpdated).getTime();
  if (!isNaN(d) && d < cutoff)
    WARNINGS.push(`Page "${page.slug}": not updated in ${STALE_DAYS}+ days (${page.lastUpdated})`);
}

// 4. Required coverage
for (const req of REQUIRED_SLUGS) {
  if (!allSlugs.has(req))
    ERRORS.push(`Missing required doc page: "${req}"`);
}

// ── Report ────────────────────────────────────────────────────────────────────
const covered = REQUIRED_SLUGS.filter(s => allSlugs.has(s)).length;
const pct = Math.round((covered / REQUIRED_SLUGS.length) * 100);

console.log(`\n  Total doc pages  : ${pages.length}`);
console.log(`  Required slugs   : ${REQUIRED_SLUGS.length}`);
console.log(`  Coverage         : ${covered}/${REQUIRED_SLUGS.length} (${pct}%)`);

if (ERRORS.length) {
  console.log(`\n❌ ${ERRORS.length} error(s):`);
  ERRORS.forEach(e => console.log(`   • ${e}`));
}
if (WARNINGS.length) {
  console.log(`\n⚠️  ${WARNINGS.length} warning(s):`);
  WARNINGS.forEach(w => console.log(`   • ${w}`));
}
if (!ERRORS.length && !WARNINGS.length) {
  console.log('\n✅ All checks passed!\n');
} else {
  console.log('');
}

process.exit(ERRORS.length > 0 ? 1 : 0);
