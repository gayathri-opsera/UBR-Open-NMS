// ── UBR NMS Documentation Types ──────────────────────────────────────────────

export type DocPersona =
  | 'Admin'
  | 'Operator'
  | 'Viewer'
  | 'descriptor_admin'
  | 'descriptor_author'
  | 'All';

export interface DocSection {
  id: string;
  title: string;
  icon: string;
  pages: DocPage[];
  requiresRole?: DocPersona[];
  defaultCollapsed?: boolean;
}

export interface DocPage {
  slug: string;
  title: string;
  description: string;
  readTime: number;           // minutes (250 words/min)
  content: string;            // Markdown
  appRoute?: string;          // /v2/alarms etc.
  personas?: DocPersona[];
  subpages?: DocPage[];
  faqs?: DocFaqItem[];
  faqTitle?: string;
  lastUpdated: string;        // ISO date "2026-11-06"
  autoGenerated?: boolean;
}

export interface DocFaqItem {
  question: string;
  answer: string;             // Markdown
}

export interface DocSearchEntry {
  slug: string;
  title: string;
  description: string;
  sectionTitle: string;
  content: string;
}
