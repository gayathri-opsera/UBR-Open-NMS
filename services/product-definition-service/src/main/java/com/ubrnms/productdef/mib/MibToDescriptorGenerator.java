package com.ubrnms.productdef.mib;

import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.time.Instant;
import java.util.*;
import java.util.stream.Collectors;

/**
 * Converts a {@link ParsedMibResult} into a discovery XML descriptor.
 *
 * <h2>Generated XML format</h2>
 * The output uses {@code xmlns="urn:nms:productdef:1.0"} and is accepted by
 * the existing {@link com.ubrnms.productdef.validation.XmlProductDefinitionParser}
 * without any changes. It can be submitted directly to the {@code /upload} endpoint
 * to enter the normal Validate → Stage → Activate lifecycle.
 *
 * <h2>Key improvements over hand-built XML</h2>
 * <ul>
 *   <li><b>Correct data types</b> — every object carries its real MIB SYNTAX
 *       (INTEGER, STRING, IPADDRESS, ENUM, etc.) instead of always being "enum".</li>
 *   <li><b>Correct index structure</b> — scalars have no instance suffix comment;
 *       table columns are annotated with their index count (SINGLE_INDEX, etc.)
 *       so the gateway SNMP walker applies the correct walk strategy.</li>
 *   <li><b>ENUM values</b> — only genuine INTEGER enumerations carry enum values;
 *       plain INTEGER or STRING objects do not.</li>
 *   <li><b>Access rights</b> — read-only objects are flagged {@code <readOnly>true</readOnly>};
 *       read-write objects allow writes.</li>
 * </ul>
 *
 * <h2>OID suffix policy (Section 5 of requirements)</h2>
 * <pre>
 *   Scalar        → OID stored as-is; gateway appends .0 at poll time
 *   Single-index  → OID stored as-is; gateway walks for all instances
 *   Double-index  → OID stored as-is; gateway walks for all instances
 *   Triple-index  → OID stored as-is; gateway walks for all instances
 * </pre>
 * The gateway's SNMP walk engine handles instance enumeration; the XML only
 * needs to declare the column OID and the index type annotation.
 */
@Slf4j
@Component
public class MibToDescriptorGenerator {

    /**
     * Generates the discovery XML from a parsed MIB result.
     *
     * @param result  output of {@link MibParser#parse}
     * @return XML string ready for upload to the product-definition service
     */
    public String generate(ParsedMibResult result) {
        StringBuilder xml = new StringBuilder(4096);

        // ── Document header ──────────────────────────────────────────────────
        xml.append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        xml.append("<!-- Generated by NMS MIB Importer from ").append(esc(result.getModuleName())).append("\n");
        xml.append("     Generated at: ").append(Instant.now()).append("\n");
        xml.append("     Objects: ").append(result.getTotalObjects())
           .append(" (").append(result.getScalarCount()).append(" scalar, ")
           .append(result.getSingleIndexCount()).append(" single-index, ")
           .append(result.getDoubleIndexCount()).append(" double-index, ")
           .append(result.getTripleIndexCount()).append(" triple-index)")
           .append(" -->\n");
        xml.append("<productDefinition xmlns=\"urn:nms:productdef:1.0\" schemaVersion=\"1.0\">\n\n");

        // ── Identity ─────────────────────────────────────────────────────────
        xml.append("  <!-- ══════════════ IDENTITY ══════════════ -->\n");
        xml.append("  <identity>\n");
        xml.append("    <id>").append(esc(buildDefinitionId(result.getVendor(), result.getProductLine()))).append("</id>\n");
        xml.append("    <vendor>").append(esc(result.getVendor())).append("</vendor>\n");
        xml.append("    <model>").append(esc(result.getProductLine())).append("</model>\n");
        xml.append("    <description>Auto-generated from MIB: ").append(esc(result.getModuleName())).append("</description>\n");
        xml.append("    <firmwareVer>1.0</firmwareVer>\n");
        xml.append("  </identity>\n\n");

        // ── Fingerprints ─────────────────────────────────────────────────────
        xml.append("  <!-- ══════════════ FINGERPRINTS ══════════════ -->\n");
        xml.append("  <fingerprints>\n");
        if (result.getEnterpriseOid() != null && !result.getEnterpriseOid().isEmpty()) {
            xml.append("    <fingerprint type=\"sysObjectId\" match=\"")
               .append(esc(result.getEnterpriseOid())).append(".*\"/>\n");
        }
        xml.append("  </fingerprints>\n\n");

        // ── Protocols ────────────────────────────────────────────────────────
        xml.append("  <!-- ══════════════ PROTOCOLS ══════════════ -->\n");
        xml.append("  <protocols>\n");
        xml.append("    <protocol name=\"primary\" type=\"snmp\">\n");
        xml.append("      <version>v2c</version>\n");
        xml.append("      <community>public</community>\n");
        xml.append("      <port>161</port>\n");
        xml.append("    </protocol>\n");
        xml.append("  </protocols>\n\n");

        // ── Parameter groups ─────────────────────────────────────────────────
        xml.append("  <!-- ══════════════ PARAMETER GROUPS ══════════════ -->\n");
        xml.append("  <!-- Indexing types:\n");
        xml.append("       SCALAR       = non-table object; gateway appends .0 at poll time\n");
        xml.append("       SINGLE_INDEX = one-level table (e.g. per-radio); gateway walks\n");
        xml.append("       DOUBLE_INDEX = two-level table (e.g. per-radio per-station); gateway walks\n");
        xml.append("       TRIPLE_INDEX = three-level table; gateway walks\n");
        xml.append("  -->\n");
        xml.append("  <parameterGroups>\n\n");

        // Group objects by section then subSection
        Map<String, Map<String, List<MibObject>>> grouped = groupObjects(result.getObjects());

        for (Map.Entry<String, Map<String, List<MibObject>>> sectionEntry : grouped.entrySet()) {
            String section = sectionEntry.getKey();
            Map<String, List<MibObject>> subGroups = sectionEntry.getValue();

            xml.append("    <!-- ── Section: ").append(section.toUpperCase()).append(" ── -->\n");

            for (Map.Entry<String, List<MibObject>> subEntry : subGroups.entrySet()) {
                String subSection = subEntry.getKey();
                List<MibObject> objs = subEntry.getValue();
                String groupId = buildGroupId(section, subSection);
                String displayName = buildDisplayName(section, subSection);

                xml.append("    <parameterGroup id=\"").append(esc(groupId)).append("\">\n");
                xml.append("      <!-- ").append(objs.size()).append(" parameters -->\n");

                for (MibObject obj : objs) {
                    appendParameter(xml, obj, groupId);
                }

                xml.append("    </parameterGroup>\n\n");
            }
        }

        xml.append("  </parameterGroups>\n\n");
        xml.append("</productDefinition>\n");

        return xml.toString();
    }

    // ── Parameter XML element ─────────────────────────────────────────────────

    private void appendParameter(StringBuilder xml, MibObject obj, String groupId) {
        // Sanitize parameter ID
        String paramId = buildParamId(obj.getName());

        xml.append("      <parameter id=\"").append(esc(paramId)).append("\">\n");

        // Display name from MIB object name (camelCase → human readable)
        String displayName = camelToDisplay(obj.getName());
        xml.append("        <name>").append(esc(displayName)).append("</name>\n");

        // Group reference
        xml.append("        <group>").append(esc(groupId)).append("</group>\n");

        // Data type — the core fix: correct type from MIB SYNTAX
        xml.append("        <dataType>").append(esc(obj.getNmsDataType().toLowerCase())).append("</dataType>\n");

        // OID
        if (obj.getOid() != null) {
            xml.append("        <oid>").append(esc(obj.getOid())).append("</oid>\n");
        }

        // Index type annotation — critical for gateway SNMP walk strategy
        xml.append("        <indexType>").append(obj.getIndexType().name()).append("</indexType>\n");

        // Index count annotation
        if (!obj.getIndexNames().isEmpty()) {
            xml.append("        <indexCount>").append(obj.getIndexNames().size()).append("</indexCount>\n");
            xml.append("        <indexNames>").append(String.join(",", obj.getIndexNames())).append("</indexNames>\n");
        }

        // Read-only flag
        boolean isReadOnly = "read-only".equalsIgnoreCase(obj.getAccess())
                || "not-accessible".equalsIgnoreCase(obj.getAccess())
                || "accessible-for-notify".equalsIgnoreCase(obj.getAccess());
        xml.append("        <readOnly>").append(isReadOnly).append("</readOnly>\n");

        // Units
        if (obj.getUnits() != null && !obj.getUnits().isBlank()) {
            xml.append("        <unit>").append(esc(obj.getUnits())).append("</unit>\n");
        }

        // Description
        if (obj.getDescription() != null && !obj.getDescription().isBlank()) {
            xml.append("        <description>").append(esc(obj.getDescription())).append("</description>\n");
        }

        // ENUM values — only for genuine enumerations (not every INTEGER)
        if ("ENUM".equals(obj.getNmsDataType()) && !obj.getEnumValues().isEmpty()) {
            xml.append("        <enumValues>\n");
            for (String label : obj.getEnumValues().keySet()) {
                xml.append("          <value>").append(esc(label)).append("</value>\n");
            }
            xml.append("        </enumValues>\n");
        }

        // UI widget hint
        String widget = resolveWidget(obj);
        xml.append("        <uiWidget>").append(widget).append("</uiWidget>\n");

        xml.append("      </parameter>\n");
    }

    // ── Grouping logic ────────────────────────────────────────────────────────

    /**
     * Groups objects by section then subSection.
     * Sections are ordered: configuration, network, management, monitor.
     */
    private Map<String, Map<String, List<MibObject>>> groupObjects(List<MibObject> objects) {
        // Ordered section map
        Map<String, Map<String, List<MibObject>>> result = new LinkedHashMap<>();
        List<String> sectionOrder = List.of("configuration", "network", "management", "monitor");

        // Initialize sections in order
        for (String s : sectionOrder) result.put(s, new LinkedHashMap<>());

        for (MibObject obj : objects) {
            String section = obj.getSection() != null ? obj.getSection() : "configuration";
            String subSection = obj.getSubSection() != null ? obj.getSubSection() : section;

            // Ensure section exists (catches any unexpected section values)
            result.computeIfAbsent(section, k -> new LinkedHashMap<>());
            result.get(section).computeIfAbsent(subSection, k -> new ArrayList<>()).add(obj);
        }

        // Remove empty sections
        result.entrySet().removeIf(e -> e.getValue().isEmpty());
        return result;
    }

    // ── Naming helpers ────────────────────────────────────────────────────────

    private String buildDefinitionId(String vendor, String productLine) {
        return (vendor + "-" + productLine)
                .toLowerCase()
                .replaceAll("[^a-z0-9]+", "-")
                .replaceAll("^-|-$", "");
    }

    private String buildGroupId(String section, String subSection) {
        if (subSection.equals(section)) return section;
        // e.g. "configuration.radio" → "radio"
        return subSection.contains(".") ? subSection.substring(subSection.lastIndexOf('.') + 1) : subSection;
    }

    private String buildDisplayName(String section, String subSection) {
        String last = subSection.contains(".") ? subSection.substring(subSection.lastIndexOf('.') + 1) : subSection;
        return Character.toUpperCase(last.charAt(0)) + last.substring(1).replace("_", " ");
    }

    private String buildParamId(String name) {
        // Convert camelCase to snake_case for stable IDs
        return name
                .replaceAll("([A-Z])", "_$1")
                .toLowerCase()
                .replaceAll("^_", "")
                .replaceAll("[^a-z0-9_]+", "_");
    }

    /** Converts camelCase MIB name to human-readable display name. */
    private String camelToDisplay(String name) {
        // Insert spaces before uppercase letters
        String spaced = name.replaceAll("([A-Z])", " $1").trim();
        // Capitalize first letter
        if (spaced.isEmpty()) return name;
        return Character.toUpperCase(spaced.charAt(0)) + spaced.substring(1);
    }

    private String resolveWidget(MibObject obj) {
        if ("ENUM".equals(obj.getNmsDataType()))    return "dropdown";
        if ("BOOLEAN".equals(obj.getNmsDataType())) return "toggle";
        if ("read-only".equalsIgnoreCase(obj.getAccess())
                || "accessible-for-notify".equalsIgnoreCase(obj.getAccess())) return "readonly";
        return "textfield";
    }

    // ── XML escaping ──────────────────────────────────────────────────────────

    private String esc(String s) {
        if (s == null) return "";
        return s.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&apos;");
    }
}
